/**
 * Returns the authentic Aarti for any deity ID with fallback to Ganesha or Shiva
 */
export function getDeityAarti(godId: string): DeityAartiEntry {
  if (DEITY_AARTIS_DATA[godId]) {
    return DEITY_AARTIS_DATA[godId];
  }

  // Graceful smart matching:
  // If user opened an avatar or form of Vishnu
  const isVishnuAvatar = ['kurma', 'matsya', 'kalki', 'narasimha', 'varaha', 'vamana', 'parashurama', 'balarama', 'venkateswara', 'jagannath', 'dhanvantari'].includes(godId);
  if (isVishnuAvatar && DEITY_AARTIS_DATA[godId]) {
    return DEITY_AARTIS_DATA[godId];
  } else if (isVishnuAvatar) {
    return {
      ...DEITY_AARTIS_DATA['vishnu'],
      godId,
    };
  }

  // If user opened a form of Shiva
  if (['kalabhairava', 'rudra', 'lingam'].includes(godId)) {
    return DEITY_AARTIS_DATA[godId] || {
      ...DEITY_AARTIS_DATA['shiva'],
      godId,
    };
  }

  // If user opened a form of Devi
  if (['tuljabhavani', 'kolhapur_ambabai', 'annapurna', 'gayatri', 'kamakhya', 'kali', 'durga'].includes(godId)) {
    return DEITY_AARTIS_DATA[godId] || {
      ...DEITY_AARTIS_DATA['parvati'],
      godId,
    };
  }

  // Default to Lord Ganesha (Pratham Pujya)
  return DEITY_AARTIS_DATA['ganesha'];
}
